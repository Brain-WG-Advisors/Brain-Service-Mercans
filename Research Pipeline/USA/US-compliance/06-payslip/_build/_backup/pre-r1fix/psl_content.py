def dd_for(code, label, side):
    """DD field names for a payslip line, or ([], reason) when the amount is a payroll result with no DD input."""
    lab = label
    if code.startswith("US-") and re.search(r"State income tax withholding", lab):
        extra = ["Connecticut withholding code (CT-W4)"] if "Connecticut" in lab else []
        return ST_TAX + extra, ""
    if code in ("US-001", "US-002", "US-003"):
        return W4, ""
    if code in ("21900", "US-006", "US-008"):
        return ["Nonresident alien flag", "Totalization agreement FICA exemption", "Employee special population category"], ""
    if code == "US-043":
        return ["Primary Treasury Tipped Occupation Code", "Secondary Treasury Tipped Occupation Code"], ""
    if code == "US-069":
        return ["Income withholding order address"], ""
    if code.startswith("US-"):
        for rx, f in LOCAL_RULES:
            if re.search(rx, lab):
                return f, ""
        for rx, f in PROGRAMME_RULES:
            if re.search(rx, lab):
                return f, ""
    if side == "NONE":
        return GENERAL_EARN, ""
    return [], "payroll input or result of the wage type; no DD master-data field holds the amount"


