changed = []

def facts(st):
    return json.load(open(os.path.join(R, 'CCG-annex_%s-facts.json' % st), encoding='utf-8'))

def line(x):
    u = x.get('unit_of_measure') or x.get('currency') or ''
    v = x['value']
    s = '- `%s` = **%s**%s (%s -> %s) [%s, %s, %s, conf %s]' % (x['key'], v, (' ' + u) if u else '', x['effective_from'],
                                                              x.get('effective_to') or 'open', x['tier'], x['register_id'], x['verification_method'], x['confidence'])
    if x.get('_level'):
        s += ' LEVEL: ' + x['_level'] + '.'
    if x.get('note'):
        s += ' ' + x['note']
    return s

def new_lines(d, prefix=None, exclude_prefix=None):
    out = []
    for x in d['facts']:
        if not x.get('_qa_r1b'):
            continue
        if prefix and not x['key'].startswith(prefix):
            continue
        if exclude_prefix and x['key'].startswith(exclude_prefix):
            continue
        out.append(line(x))
    return out

def open_q(d):
    o = ['## Open questions', '', 'Mirrors `unresolved[]` in the facts file (same keys, same wording). Regenerated by QA r1b on %s.' % TODAY, '']
    for u in d['unresolved']:
        o.append('- `%s` (%s) — %s **Would close it:** %s' % (u['key'], 'blocking' if u.get('blocking') else 'non-blocking', u['why'], u['what_would_close_it']))
    if not d['unresolved']:
        o.append('- None outstanding.')
    return '\n'.join(o) + '\n'

def rewrite(st, block, subs=()):
    p = os.path.join(R, 'CCG-annex_%s-research-pack.md' % st)
    t = open(p, encoding='utf-8').read()
    for a, b in subs:
        n = len(re.findall(a, t, flags=re.M))
        assert n >= 1, (st, a)
        t = re.sub(a, lambda m: b, t, flags=re.M)
    i = t.index('\n## Open questions')
    t = t[:i].rstrip('\n') + '\n\n' + block.strip('\n') + '\n\n' + open_q(facts(st))
    open(p, 'w', encoding='utf-8').write(t)
    changed.append(p)

