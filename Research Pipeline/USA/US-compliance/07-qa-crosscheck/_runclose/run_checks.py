# Run-close battery (stages 8-9). Outputs to 07-qa-crosscheck/_runclose/out. No stdin.
import os, subprocess, sys, json
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, "out")
BASE = os.path.abspath(os.path.join(HERE, "..", ".."))
SH = os.path.expanduser("~/mercans-pipeline/shared")
ENV = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUTF8="1", PYTHONDONTWRITEBYTECODE="1")
only = sys.argv[1:]
def run(name, cmd, cwd=BASE):
    if only and name not in only: return
    p = subprocess.run([sys.executable] + cmd, cwd=cwd, env=ENV, capture_output=True, text=True, encoding="utf-8", stdin=subprocess.DEVNULL, timeout=3000)
    txt = (p.stdout or "") + (p.stderr or "")
    open(os.path.join(OUT, name + ".log"), "w", encoding="utf-8").write(txt)
    print(f"[{name}] rc={p.returncode} :: " + " | ".join(l for l in txt.strip().splitlines()[-6:])[:600])
o = lambda n: os.path.join(OUT, n)
B = lambda *a: os.path.join(BASE, *a)
