# -*- coding: utf-8 -*-
"""
make_classification.py - builds CO-DD-001-classification.md.

Classifies every distinct System Mapping used across the six in-scope Colombian
report specifications into DD / TX / CALC / SYS and reconciles the DD bucket
against the fields actually carried in CO-DD-001-v1.0.xlsx.

  DD   - user-input master data -> belongs in the Data Dictionary
  TX   - an earning or deduction amount -> belongs in the Wage Type Catalogue
  CALC - derived value, total, statutory rate, ceiling or apportionment
         computed by the engine -> parameters / calculation layer
  SYS  - system, period, sequence, environment or authority-generated value

Run: python make_classification.py
"""

import glob
import os
import re
from collections import OrderedDict

from openpyxl import load_workbook

HERE = os.path.dirname(os.path.abspath(__file__))
SPECS = os.path.join(HERE, "..", "04-reports-spec")
DD = os.path.join(HERE, "CO-DD-001-v1.0.xlsx")
OUT = os.path.join(HERE, "CO-DD-001-classification.md")


def classify(sm):
    s = sm.strip()
    if s.startswith(("SUM(", "COUNT(", "Casilla ")) or re.match(r"^(NIE|T2R2)\S*\s*[-+]", s):
        return "CALC"
    if s.startswith("(derived") or s.startswith("(system"):
        return "CALC"
    if s.startswith("(mirrors") or s.startswith("(references") or s.startswith("(not an input"):
        return "SYS"
    if s.startswith("Constant"):
        return "SYS"
    if s.startswith("System.") or s.startswith("PayPeriod."):
        return "SYS"
    if s.startswith("(client"):
        return "SYS"
    if s.startswith("(employee"):
        # Formulario 220 section-2 declarations: amounts of NON-employment income
        # and asset/debt figures declared by the employee, plus the signature.
        return "CALC"
    if s.startswith("Mercans."):
        return "CALC"
    if s.startswith("Payroll."):
        return "TX"
    if s.startswith(("Company.", "Employee.", "Contract.")):
        # amounts carried under a master-data prefix are still amounts
        if re.search(r"(Gross|Withholding|Contractual_Salary)", s):
            return "TX"
        return "DD"
    return "SYS"


def main():
    rows = OrderedDict()
    for f in sorted(glob.glob(os.path.join(SPECS, "CO-*-Spec.xlsx"))):
        short = os.path.basename(f).replace("-Spec.xlsx", "")
        wb = load_workbook(f, data_only=True)
        for sname in [x for x in wb.sheetnames if "Spec" in x]:
            ws = wb[sname]
            hdr = None
            for r in range(1, 8):
                if ws.cell(r, 1).value == "Field Name (EN)":
                    hdr = r
                    break
            if hdr is None:
                continue
            for r in range(hdr + 1, ws.max_row + 1):
                sm = (ws.cell(r, 12).value or "").strip()
                if not sm:
                    continue
                rec = rows.setdefault(sm, {"e": set(), "specs": set(), "en": ws.cell(r, 1).value})
                rec["e"].add(ws.cell(r, 5).value)
                rec["specs"].add(short.split("-")[1])

    # DD fields actually present
    wb = load_workbook(DD)
    dd_names = []
    for sheet, col in (("ID Information", 3), ("Country Fields", 4)):
        ws = wb[sheet]
        for r in range(1, ws.max_row + 1):
            v = ws.cell(r, col).value
            if v and v != "Field Name":
                dd_names.append(v)

    counts = {"DD": 0, "TX": 0, "CALC": 0, "SYS": 0}
    lines = []
    for sm, rec in sorted(rows.items()):
        b = classify(sm)
        counts[b] += 1
        lines.append((b, sm, rec))

    mismatch = [(sm, rec) for b, sm, rec in lines
                if (b == "DD") != ("Y" in rec["e"])]

    with open(OUT, "w", encoding="utf-8") as fh:
        w = fh.write
        w("# CO-DD-001 - spec field classification (DD / TX / CALC / SYS)\n\n")
        w("Generated by `make_classification.py` from the six in-scope report specifications in "
          "`04-reports-spec`. One row per distinct **System Mapping**.\n\n")
        w("| Bucket | Meaning | Distinct system mappings |\n|---|---|---|\n")
        w("| **DD** | User-input master data | %d |\n" % counts["DD"])
        w("| **TX** | Earning or deduction amount -> Wage Type Catalogue | %d |\n" % counts["TX"])
        w("| **CALC** | Derived value, total, statutory rate, ceiling or apportionment | %d |\n"
          % counts["CALC"])
        w("| **SYS** | System, period, sequence, environment or authority-generated value | %d |\n\n"
          % counts["SYS"])
        w("Total distinct system mappings: **%d**. Data Dictionary fields delivered: **%d** "
          "(%d on *ID Information*, %d on *Country Fields*).\n\n"
          % (len(rows), len(dd_names), 17, len(dd_names) - 17))

        w("## Lock-step against the spec column E flag\n\n")
        if not mismatch:
            w("No divergence: every mapping classified **DD** here carries "
              "`Payroll Field (Y/N) = Y` in the specifications, and vice versa.\n\n")
        else:
            w("The following mappings diverge between this classification and the spec column E "
              "flag. Each divergence is deliberate and is explained below.\n\n")
            w("| System Mapping | Spec col E | Classified here | Reason |\n|---|---|---|---|\n")
            for sm, rec in mismatch:
                reason = ("AMOUNT. CLAUDE.md routes base / contractual salary to the Wage Type "
                          "Catalogue, not to the Data Dictionary. Excluded from CO-DD-001."
                          if "Contractual_Salary" in sm else "See notes.")
                w("| `%s` | %s | %s | %s |\n"
                  % (sm, "/".join(sorted(str(x) for x in rec["e"])), classify(sm), reason))
            w("\n")

        for bucket, title in (("DD", "DD - Data Dictionary master data"),
                              ("TX", "TX - Wage Type Catalogue (amounts)"),
                              ("CALC", "CALC - derived values, rates, ceilings, totals"),
                              ("SYS", "SYS - system, period and authority-generated values")):
            w("## %s\n\n" % title)
            w("| System Mapping | Spec field name (EN) | Specs |\n|---|---|---|\n")
            for b, sm, rec in lines:
                if b != bucket:
                    continue
                w("| `%s` | %s | %s |\n"
                  % (sm, (rec["en"] or "").replace("|", "/"), ", ".join(sorted(rec["specs"]))))
            w("\n")

    print("Wrote:", OUT)
    print("  buckets:", counts, "| distinct mappings:", len(rows),
          "| DD fields delivered:", len(dd_names))
    if mismatch:
        print("  deliberate lock-step divergences:", [m[0] for m in mismatch])


if __name__ == "__main__":
    main()
