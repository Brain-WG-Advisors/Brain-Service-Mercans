def _load_wtc():
    wb = openpyxl.load_workbook(WTC_XLSX, read_only=True, data_only=True)
    rows = list(wb["Wage Type Catalogue"].iter_rows(values_only=True))[1:]
    return {str(r[0]): {"label": r[1], "category": r[4]} for r in rows if r[0]}


def _load_dd():
    wb = openpyxl.load_workbook(DD_XLSX, read_only=True, data_only=True)
    names = {}
    for sh, ci in (("ID Information", 2), ("Country Fields", 3)):
        for r in wb[sh].iter_rows(min_row=5, values_only=True):
            if len(r) > ci and r[ci] and r[ci] != "Field Name":
                names[str(r[ci]).strip()] = sh
    return names


