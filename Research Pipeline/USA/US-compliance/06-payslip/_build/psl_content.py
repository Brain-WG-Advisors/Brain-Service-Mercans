def catalogue():
    """[(code, label, section)] of every wage type with payslip: true, in crosswalk order."""
    out = []
    for code, e in CW.items():
        if not e.get("payslip"):
            continue
        assert code in WTC, f"{code} not in the WTC"
        sec = {"EE": "Employee deductions", "ER": "Employer contributions", "NONE": "Earnings"}[e["side"]]
        out.append((code, e["label"], sec, e["side"]))
    return out


# ------------------------------------------------------------------ state rule helpers ---
STATES = sorted(S.STATE_NAMES)


def st_keys(kind):
    """{state: key} for psl.<st>.statement.<kind> facts."""
    out = {}
    for k in S.C.FACTS:
        m = re.match(r"^psl\.([a-z]{2})\.statement\.(%s)$" % kind, k)
        if m:
            out[m.group(1).upper()] = k
    return out


def states_naming(pattern, kinds=("content", "scope"), extra=()):
    """States whose usable statement fact names the element (regex over the fact text). Binding: every key used is
    noted against the current location; only usable facts count."""
    rx = re.compile(pattern, re.I)
    hits = []
    for kind in kinds:
        for stc, k in st_keys(kind).items():
            ok, _ = S.usable(k)
            if ok and rx.search(str(S.fact(k)["value"])):
                S.note_use(k)
                hits.append(stc)
    for stc, k in extra:
        ok, _ = S.usable(k)
        if ok and rx.search(str(S.fact(k)["value"])):
            S.note_use(k)
            hits.append(stc)
    return sorted(set(hits))


def named(stl):
    return ("Rows naming this element in Field Option, block STATE_STATEMENT_RULE: " + ", ".join(stl) + ".") if stl else ""


